"""
CardioPulse Report Generator
Produces formal Patient Health Analysis Reports in JSON and downloadable PDF formats.
"""

import os
from datetime import datetime, timezone
from typing import Dict, Any, Optional
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

class HealthReportGenerator:
    
    @staticmethod
    def generate_report_payload(
        patient_data: Dict[str, Any],
        reading_data: Dict[str, Any],
        triage_data: Dict[str, Any],
        ai_data: Dict[str, Any],
        historical_stats: Dict[str, Any],
        reference_code: str
    ) -> Dict[str, Any]:
        """
        Builds the 12-section clinical decision support health report data structure.
        """
        now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        
        report_data = {
            "reference_code": reference_code,
            "generated_at": now,
            "title": "PATIENT HEALTH ANALYSIS REPORT - CLINICAL DECISION SUPPORT",
            "section_1_patient_details": {
                "patient_id_code": patient_data.get("patient_id_code", "N/A"),
                "full_name": patient_data.get("full_name", "Anonymous"),
                "age": patient_data.get("age", "N/A"),
                "sex": patient_data.get("sex", "N/A"),
                "height_cm": patient_data.get("height_cm"),
                "weight_kg": patient_data.get("weight_kg"),
                "emergency_contact": f"{patient_data.get('emergency_contact_name', 'N/A')} ({patient_data.get('emergency_contact_phone', 'N/A')})"
            },
            "section_2_measurement_details": {
                "measurement_time": reading_data.get("measurement_time", now),
                "measurement_method": reading_data.get("measurement_method", "Manual Entry"),
                "device_name": reading_data.get("device_name", "Sphygmomanometer / Optical Pulse"),
                "resting_status": reading_data.get("resting_status", "resting")
            },
            "section_3_current_heart_rate": {
                "bpm": reading_data.get("bpm"),
                "expected_min_bpm": triage_data.get("expected_min_bpm", 60),
                "expected_max_bpm": triage_data.get("expected_max_bpm", 100),
                "status_label": triage_data.get("alert_title", "Normal")
            },
            "section_4_historical_comparison": {
                "7d_average_bpm": historical_stats.get("avg_hr", "Insufficient Data"),
                "7d_min_bpm": historical_stats.get("min_hr", "N/A"),
                "7d_max_bpm": historical_stats.get("max_hr", "N/A"),
                "trend_interpretation": ai_data.get("unusual_patterns", ["No longitudinal deviations"])
            },
            "section_5_patient_symptoms": reading_data.get("symptoms", {}),
            "section_6_medical_history_considerations": {
                "known_conditions": patient_data.get("medical_history", {}),
                "active_medications": [m.get("name") for m in patient_data.get("medications", [])],
                "allergies": [a.get("allergen") for a in patient_data.get("allergies", [])]
            },
            "section_7_ai_assisted_observations": {
                "contextual_interpretation": ai_data.get("contextual_interpretation", ""),
                "contributing_physiological_factors": ai_data.get("physiological_factors", [])
            },
            "section_8_potential_risk_indicators": {
                "alert_level": triage_data.get("alert_level", "GREEN"),
                "clinical_rationale": triage_data.get("clinical_rationale", ""),
                "triage_category": triage_data.get("triage_category", "routine")
            },
            "section_9_recommended_next_steps": ai_data.get("recommendations", []),
            "section_10_emergency_warnings": {
                "is_emergency": triage_data.get("alert_level") == "RED",
                "emergency_actions": triage_data.get("emergency_actions", []),
                "hotline": triage_data.get("hotline_number", "112")
            },
            "section_11_limitations_of_analysis": ai_data.get("data_limitations", "Pulse rate cannot diagnose ECG arrhythmia."),
            "section_12_disclaimer": (
                "LEGAL & CLINICAL DISCLAIMER: This report is generated by the CardioPulse AI Clinical Decision Support System "
                "for educational and preliminary assessment purposes only. It does NOT constitute a clinical diagnosis, "
                "prescription, or medical prognosis. Diagnosis requires direct evaluation by a qualified healthcare professional."
            )
        }
        return report_data

    @staticmethod
    def generate_pdf(report_data: Dict[str, Any], output_path: str) -> str:
        """
        Renders a clean, clinical PDF document using ReportLab.
        """
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        doc = SimpleDocTemplate(
            output_path,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )
        
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#0f172a"),
            alignment=1
        )
        subtitle_style = ParagraphStyle(
            'ReportSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#475569"),
            alignment=1
        )
        section_heading = ParagraphStyle(
            'SectionHead',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=11,
            leading=14,
            textColor=colors.HexColor("#0f766e"),
            spaceBefore=8,
            spaceAfter=4
        )
        body_style = ParagraphStyle(
            'Body',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#1e293b")
        )
        disclaimer_style = ParagraphStyle(
            'Disclaimer',
            parent=styles['Italic'],
            fontName='Helvetica-Oblique',
            fontSize=8,
            leading=10,
            textColor=colors.HexColor("#64748b")
        )
        
        story = []
        
        # Header Clinic Banner
        story.append(Paragraph("CARDIOPULSE CLINICAL DECISION SUPPORT PLATFORM", title_style))
        story.append(Paragraph(f"PATIENT HEALTH ANALYSIS REPORT • Ref: {report_data.get('reference_code')} • Generated: {report_data.get('generated_at')}", subtitle_style))
        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0d9488"), spaceAfter=10))

        # Alert Level Badge Table
        alert_lvl = report_data.get("section_8_potential_risk_indicators", {}).get("alert_level", "GREEN")
        badge_color = colors.HexColor("#16a34a") # Green
        if alert_lvl == "YELLOW":
            badge_color = colors.HexColor("#ca8a04")
        elif alert_lvl == "ORANGE":
            badge_color = colors.HexColor("#ea580c")
        elif alert_lvl == "RED":
            badge_color = colors.HexColor("#dc2626")

        badge_data = [[
            Paragraph(f"<b>TRIAGE SAFETY STATUS: {alert_lvl}</b>", ParagraphStyle('B', textColor=colors.white, alignment=1, fontSize=11, fontName='Helvetica-Bold')),
            Paragraph(f"<b>RECORDED HEART RATE: {report_data.get('section_3_current_heart_rate', {}).get('bpm')} BPM</b> (Ref: {report_data.get('section_3_current_heart_rate', {}).get('expected_min_bpm')}–{report_data.get('section_3_current_heart_rate', {}).get('expected_max_bpm')} BPM)", ParagraphStyle('B2', textColor=colors.HexColor("#0f172a"), alignment=1, fontSize=10, fontName='Helvetica-Bold'))
        ]]
        badge_table = Table(badge_data, colWidths=[200, 340])
        badge_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, 0), badge_color),
            ('BACKGROUND', (1, 0), (1, 0), colors.HexColor("#f1f5f9")),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#94a3b8")),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(badge_table)
        story.append(Spacer(1, 10))

        # 1. Patient Demographics & Measurement Details in 2-column table
        p_info = report_data.get("section_1_patient_details", {})
        m_info = report_data.get("section_2_measurement_details", {})
        info_table_data = [
            [Paragraph("<b>Patient Name:</b>", body_style), Paragraph(str(p_info.get("full_name")), body_style),
             Paragraph("<b>Measurement Method:</b>", body_style), Paragraph(str(m_info.get("measurement_method")), body_style)],
            [Paragraph("<b>Patient ID:</b>", body_style), Paragraph(str(p_info.get("patient_id_code")), body_style),
             Paragraph("<b>Activity Status:</b>", body_style), Paragraph(str(m_info.get("resting_status")), body_style)],
            [Paragraph("<b>Age / Sex:</b>", body_style), Paragraph(f"{p_info.get('age')} yrs / {p_info.get('sex')}", body_style),
             Paragraph("<b>Device Source:</b>", body_style), Paragraph(str(m_info.get("device_name")), body_style)],
            [Paragraph("<b>Emergency Contact:</b>", body_style), Paragraph(str(p_info.get("emergency_contact")), body_style),
             Paragraph("<b>Recorded Time:</b>", body_style), Paragraph(str(m_info.get("measurement_time")), body_style)],
        ]
        info_table = Table(info_table_data, colWidths=[100, 170, 120, 150])
        info_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(info_table)
        story.append(Spacer(1, 10))

        # Clinical Observations & AI Insights
        story.append(Paragraph("AI-Assisted Clinical Observations & Context", section_heading))
        obs_text = report_data.get("section_7_ai_assisted_observations", {}).get("contextual_interpretation", "")
        story.append(Paragraph(obs_text, body_style))
        story.append(Spacer(1, 6))

        # Physiological Factors
        factors = report_data.get("section_7_ai_assisted_observations", {}).get("contributing_physiological_factors", [])
        if factors:
            factor_bullets = "".join([f"• {f}<br/>" for f in factors])
            story.append(Paragraph(f"<b>Contributing Physiological Factors:</b><br/>{factor_bullets}", body_style))
            story.append(Spacer(1, 6))

        # Recommendations
        story.append(Paragraph("Clinical & Wellness Next Steps", section_heading))
        recs = report_data.get("section_9_recommended_next_steps", [])
        if recs:
            rec_content = []
            for r in recs:
                cat = r.get("category", "General").replace("_", " ").title()
                txt = r.get("recommendation_text", "")
                rec_content.append(Paragraph(f"<b>[{cat}]</b>: {txt}", body_style))
                rec_content.append(Spacer(1, 3))
            story.extend(rec_content)
        story.append(Spacer(1, 8))

        # Emergency Box (if alert is RED or ORANGE)
        if alert_lvl in ["RED", "ORANGE"]:
            emerg = report_data.get("section_10_emergency_warnings", {})
            emerg_actions = emerg.get("emergency_actions", [])
            act_text = "<br/>".join([f"• {a}" for a in emerg_actions])
            em_card = [[
                Paragraph(f"<b>URGENT CLINICAL WARNING (Emergency Hotline: {emerg.get('hotline')})</b><br/>{act_text}", ParagraphStyle('Em', textColor=colors.HexColor("#991b1b"), fontName='Helvetica-Bold', fontSize=9, leading=12))
            ]]
            em_table = Table(em_card, colWidths=[540])
            em_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#fef2f2")),
                ('BOX', (0, 0), (-1, -1), 1.5, colors.HexColor("#ef4444")),
                ('PADDING', (0, 0), (-1, -1), 8),
            ]))
            story.append(em_table)
            story.append(Spacer(1, 10))

        # Clinical Limitations & Disclaimer
        story.append(Paragraph("Clinical Limitations & Diagnostic Scope", section_heading))
        story.append(Paragraph(report_data.get("section_11_limitations_of_analysis", ""), body_style))
        story.append(Spacer(1, 8))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1"), spaceAfter=6))
        story.append(Paragraph(report_data.get("section_12_disclaimer", ""), disclaimer_style))
        story.append(Spacer(1, 12))

        # Clinician Review / Sign-off Block
        doc_block = [
            [Paragraph("<b>Attending Physician Review & Signature:</b>", body_style), Paragraph("<b>Clinical Approval Status:</b>", body_style)],
            [Paragraph("Dr. ____________________________________, MD", body_style), Paragraph("[  ] Approved as Reviewed   [  ] Follow-up Ordered", body_style)],
            [Paragraph("License #: __________________ Date: ____________", body_style), Paragraph("Notes: _____________________________________", body_style)]
        ]
        doc_table = Table(doc_block, colWidths=[270, 270])
        doc_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#94a3b8")),
            ('PADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(doc_table)

        doc.build(story)
        return output_path
